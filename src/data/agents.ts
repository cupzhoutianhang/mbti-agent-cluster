// 辅助函数：根据后端MBTI格式获取前端ID
export function getFrontendIdByMBTI(mbtiType: string): string | null {
  const entry = Object.entries(ID_MAPPING).find(([, value]) => value === mbtiType);
  return entry ? entry[0] : null;
}